$spreadsheetSupportPath = $PSScriptRoot

function Get-SpreadsheetEngineLabel($Application) {
    $folder = [string]$Application.Path
    if ([string]::IsNullOrWhiteSpace($folder)) { throw 'The workbook engine did not report its installation folder.' }

    # Excel.Application is a compatibility alias. Detect the installed binary.
    $wpsPath = Join-Path $folder 'et.exe'
    if (Test-Path -LiteralPath $wpsPath -PathType Leaf) {
        $info = (Get-Item -LiteralPath $wpsPath).VersionInfo
        if ($info.CompanyName -match 'Kingsoft') { return "WPS Spreadsheets $($info.ProductVersion)" }
    }
    $excelPath = Join-Path $folder 'EXCEL.EXE'
    if (Test-Path -LiteralPath $excelPath -PathType Leaf) {
        $info = (Get-Item -LiteralPath $excelPath).VersionInfo
        if ($info.CompanyName -match 'Microsoft') { return "Microsoft Excel $($info.ProductVersion)" }
    }
    throw 'Unable to identify the workbook engine by its installed binary.'
}

function New-TestReportCopy($Session, [string]$Path) {
    # Test generated bytes as a local fixture. This leaves the source, including
    # any browser zone metadata, untouched.
    $copy = Join-Path $Session.Root ([Guid]::NewGuid().ToString('N') + '.xlsx')
    $Session.Copies.Add($copy)
    [IO.File]::WriteAllBytes($copy, [IO.File]::ReadAllBytes($Path))
    $copy
}

function Confirm-SafeModeNotice([int]$ProcessId) {
    $condition = [Windows.Automation.PropertyCondition]::new([Windows.Automation.AutomationElement]::ProcessIdProperty, $ProcessId)
    $windows = [Windows.Automation.AutomationElement]::RootElement.FindAll([Windows.Automation.TreeScope]::Children, $condition)
    foreach ($window in $windows) {
        if ($window.Current.ClassName -ne 'NUIDialog') { continue }
        $items = $window.FindAll([Windows.Automation.TreeScope]::Descendants, [Windows.Automation.Condition]::TrueCondition)
        # Acknowledge only the notice that existing recovery files will open on
        # the next normal start. Leave recovery, activation and add-in settings alone.
        if ($items | Where-Object { $_.Current.Name -eq 'Excel 检测到存在已被恢复的文件。这些文件将在下一次以正常模式启动 Excel 时打开。' }) {
            $button = $items | Where-Object { $_.Current.Name -eq '确定' -and
                $_.Current.ControlType -eq [Windows.Automation.ControlType]::Button } | Select-Object -First 1
            if ($button) {
                $button.GetCurrentPattern([Windows.Automation.InvokePattern]::Pattern).Invoke()
                return $true
            }
        }
    }
    return $false
}

function Close-SpreadsheetTest($Session) {
    try {
        if ($Session.App) {
            $Session.App.DisplayAlerts = $false
            $Session.App.Quit()
            [void][Runtime.InteropServices.Marshal]::ReleaseComObject($Session.App)
        }
    } finally {
        if ($Session.Process -and -not $Session.Process.HasExited) {
            if (-not $Session.Process.WaitForExit(2500)) { $Session.Process.Kill(); [void]$Session.Process.WaitForExit(2500) }
        }
        foreach ($copy in $Session.Copies) {
            if (Test-Path -LiteralPath $copy -PathType Leaf) { Remove-Item -LiteralPath $copy }
        }
    }
}

function Start-SpreadsheetTest([string]$Engine, [string]$Starter) {
    if (Get-Process -Name et,excel -ErrorAction SilentlyContinue) {
        throw 'Close open spreadsheet windows before running this isolated test.'
    }
    $session = [pscustomobject]@{
        App = $null; Process = $null; Label = ''; Engine = $Engine
        Root = (Split-Path -Parent $Starter)
        Copies = [Collections.Generic.List[string]]::new()
    }
    try {
        if ($Engine -eq 'Registered') {
            $session.App = New-Object -ComObject Excel.Application
        } else {
            $paths = @()
            if ($env:ZHANGYE_EXCEL_EXE) { $paths += $env:ZHANGYE_EXCEL_EXE }
            else {
                foreach ($base in @($env:ProgramFiles, [Environment]::GetEnvironmentVariable('ProgramFiles(x86)'))) {
                    if ($base) { $paths += (Join-Path $base 'Microsoft Office/root/Office16/EXCEL.EXE') }
                }
            }
            $exePath = $paths | Where-Object { Test-Path -LiteralPath $_ -PathType Leaf } | Select-Object -First 1
            if (-not $exePath) { throw 'Microsoft Excel executable not found. Set ZHANGYE_EXCEL_EXE.' }
            $exe = Get-Item -LiteralPath $exePath
            if ($exe.VersionInfo.CompanyName -notmatch 'Microsoft') { throw 'Selected executable is not Microsoft Excel.' }
            Add-Type -AssemblyName UIAutomationClient,UIAutomationTypes
            if (-not ('MicrosoftExcelNative' -as [type])) {
                Add-Type -Path (Join-Path $spreadsheetSupportPath 'MicrosoftExcelNative.cs')
            }
            $localStarter = New-TestReportCopy $session $Starter
            $session.Process = Start-Process -FilePath $exe.FullName -ArgumentList @('/safe', ('"' + $localStarter + '"')) -WindowStyle Hidden -PassThru
            $deadline = [DateTime]::UtcNow.AddSeconds(14)
            $noticeConfirmed = $false
            $startupError = $null
            while ([DateTime]::UtcNow -lt $deadline -and -not $session.Process.HasExited) {
                try {
                    $window = [MicrosoftExcelNative]::DocumentWindow([uint32]$session.Process.Id)
                    if ($null -ne $window) {
                        $app = $window.Application
                        if ($null -ne $app -and $app.Workbooks.Count -ge 1) {
                            $session.App = $app
                            break
                        }
                    }
                    if (-not $noticeConfirmed) { $noticeConfirmed = Confirm-SafeModeNotice $session.Process.Id }
                } catch { $startupError = $_ }
                Start-Sleep -Milliseconds 250
            }
            if (-not $session.App) { throw "Microsoft Excel safe-mode workbook was unavailable. $startupError" }
            $actual = Get-Item -LiteralPath (Join-Path $session.App.Path 'EXCEL.EXE')
            if ($actual.FullName -ne $exe.FullName) { throw 'Microsoft Excel instance came from an unexpected executable.' }
            $session.App.DisplayAlerts = $false
            $session.App.Workbooks.Item(1).Close($false)
        }
        $session.Label = Get-SpreadsheetEngineLabel $session.App
        $session.App.AutomationSecurity = 3
        $session
    } catch {
        Close-SpreadsheetTest $session
        throw
    }
}

function Open-SpreadsheetReport($Session, [string]$Path) {
    if ($Session.Engine -eq 'Microsoft') { $Path = New-TestReportCopy $Session $Path }
    $Session.App.Workbooks.Open($Path, 0, $true)
}
